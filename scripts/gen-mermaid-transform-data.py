#!/usr/bin/env python3
"""Generate Lisp golden data for the mermaid markdown transformer.

Reads test/fixtures/mermaid-golden/transform-reference.json (produced by
scripts/mermaid-transform-golden.mjs from marked 18.0.5 + grok-mermaid 0.2.2)
and writes test/cadr-tui/mermaid-transform-data.lisp.

Usage:
  scripts/gen-mermaid-transform-data.py
  scripts/gen-mermaid-transform-data.py --check
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GOLDEN = ROOT / "test/fixtures/mermaid-golden/transform-reference.json"
OUT = ROOT / "test/cadr-tui/mermaid-transform-data.lisp"
EXPECTED_RESULTS = 23
REQUIRED_KEYS = {
    "id",
    "src",
    "mode",
    "messageType",
    "isStreaming",
    "availableWidth",
    "expected",
}


def lisp_string(value: str) -> str:
    out = []
    for ch in value:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\n")
        elif ch == "\r":
            out.append("\r")
        elif ch == "\t":
            out.append("\t")
        elif o < 0x20 or o == 0x7F or o in (0x2028, 0x2029):
            raise ValueError(
                f"character U+{o:04X} cannot be represented as a Lisp string escape"
            )
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def lisp_bool(value: bool) -> str:
    return "t" if value else "nil"


def generate() -> str:
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    results = golden["results"]
    if len(results) != EXPECTED_RESULTS:
        raise ValueError(
            f"transform golden count changed: expected {EXPECTED_RESULTS}, "
            f"got {len(results)}"
        )
    golden_sha = hashlib.sha256(GOLDEN.read_bytes()).hexdigest()
    seen = set()
    body = [
        ";;; Generated by scripts/gen-mermaid-transform-data.py.  Do not edit.",
        ";;; Source: test/fixtures/mermaid-golden/transform-reference.json",
        f";;; SHA-256: {golden_sha}",
        "(in-package #:cadr-tui/tests)",
        "",
        "(defparameter +mermaid-transform-results+",
        "  (list",
    ]
    for case in results:
        missing = REQUIRED_KEYS - set(case)
        if missing:
            raise ValueError(f"case {case.get('id')!r} missing {sorted(missing)}")
        case_id = case["id"]
        if case_id in seen:
            raise ValueError(f"duplicate id {case_id!r}")
        seen.add(case_id)
        if not isinstance(case["src"], str) or not isinstance(case["expected"], str):
            raise ValueError(f"case {case_id!r} src/expected must be strings")
        if not isinstance(case["availableWidth"], int):
            raise ValueError(f"case {case_id!r} availableWidth must be int")
        if not isinstance(case["isStreaming"], bool):
            raise ValueError(f"case {case_id!r} isStreaming must be bool")
        body.extend(
            [
                f"    (list :id {lisp_string(case_id)}",
                f"          :src {lisp_string(case['src'])}",
                f"          :mode {lisp_string(case['mode'])}",
                f"          :message-type {lisp_string(case['messageType'])}",
                f"          :streaming-p {lisp_bool(case['isStreaming'])}",
                f"          :available-width {case['availableWidth']}",
                f"          :expected {lisp_string(case['expected'])})",
            ]
        )
    body.extend(["  ))", ""])
    return "\n".join(body)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUT.exists():
            print(f"{OUT} is missing", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; rerun scripts/gen-mermaid-transform-data.py", file=sys.stderr)
            return 1
        print("mermaid transform data consistent")
        return 0
    tmp = Path(tempfile.mkstemp(prefix="mermaid-transform-data-", suffix=".lisp")[1])
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(OUT)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
