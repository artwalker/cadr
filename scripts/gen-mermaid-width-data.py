#!/usr/bin/env python3
"""Mechanical conversion of grok-mermaid@0.2.2 dist/width-data.js into Lisp.

Source: package/dist/width-data.js, lines 1-993 of the checked-in fixture
`test/fixtures/mermaid-golden/grok-mermaid-0.2.2.tgz` (SHA-256
61f98236a93be5f0b4f8caeb9956a728dc22b275d012b190639d3c03ae942934).

The table is transcribed verbatim: sorted, contiguous [lo, hi, width] runs
covering the whole code point space.  The script only accepts the exact
fixture layout (`export const WIDTHS = [` followed by `[0x.., 0x.., N],`
rows and a closing `];`) so a hand-edit cannot silently change the data.

Usage:
  scripts/gen-mermaid-width-data.py [path-to-width-data.js]
  scripts/gen-mermaid-width-data.py --check
"""

import argparse
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SRC = ROOT / "test/fixtures/mermaid-golden/grok-mermaid-0.2.2.tgz"
OUT = ROOT / "src/cadr-tui/mermaid/width-data.lisp"

ROW_RE = re.compile(r"^    \[0x([0-9a-f]+), 0x([0-9a-f]+), (\d+)\],$")


def extract(src: Path) -> list[tuple[int, int, int]]:
    if src.suffix == ".tgz":
        import io
        import tarfile

        with tarfile.open(src, "r:gz") as tf:
            member = tf.getmember("package/dist/width-data.js")
            text = tf.extractfile(member).read().decode("utf-8")
    else:
        text = src.read_text(encoding="utf-8")
    lines = text.splitlines()
    assert lines[0].startswith("// Generated by scripts/gen-width-data.ts"), lines[0]
    assert "export const WIDTHS = [" in text
    rows = []
    in_table = False
    for ln in lines:
        if ln == "export const WIDTHS = [":
            in_table = True
            continue
        if in_table and ln == "];":
            break
        if in_table:
            m = ROW_RE.match(ln)
            assert m, f"unexpected row line: {ln!r}"
            rows.append((int(m.group(1), 16), int(m.group(2), 16), int(m.group(3))))
    assert rows, "no rows parsed"
    # Sanity: sorted, contiguous, whole code point space.
    assert rows[0][0] == 0 and rows[-1][1] == 0x10FFFF
    for (_, hi, _), (lo, _, _) in zip(rows, rows[1:]):
        assert hi + 1 == lo, f"gap between 0x{hi:x} and 0x{lo:x}"
    return rows


def emit(rows: list[tuple[int, int, int]]) -> str:
    lines = [
        ";;; -*- mode: lisp -*-",
        ";;;",
        ";;; grok-mermaid@0.2.2 dist/width-data.js:1-993 — mechanically",
        ";;; converted by scripts/gen-mermaid-width-data.py.  Do not edit",
        ";;; by hand; regenerate with the script.",
        ";;;",
        ";;; Copyright 2023-2026 SpaceXAI",
        ";;; Copyright 2026 Alexey Zaytsev",
        ";;; Licensed under the Apache License, Version 2.0.",
        ";;; This file is a Common Lisp port by the cadr authors; it is a",
        ";;; modified version of the original work.  License text:",
        ";;; docs/third-party/grok-mermaid-LICENSE.txt",
        ";;;",
        ";;; Sorted, contiguous [lo, hi, width] runs covering the whole code",
        ";;; point space (unicode-width crate, Apache-2.0).",
        "",
        "(in-package #:cadr-tui)",
        "",
        "(defparameter +gm-widths+",
        "  #(",
    ]
    for lo, hi, w in rows:
        lines.append(f"    #(#x{lo:x} #x{hi:x} {w})")
    lines += [
        "  )",
        "  \"Sorted [lo, hi, width] runs covering the whole code point space.\")",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate to a temp file and compare with the checked-in file",
    )
    parser.add_argument("source", nargs="?", default=None)
    args = parser.parse_args()

    src = Path(args.source) if args.source else DEFAULT_SRC
    rows = extract(src)
    out = emit(rows)
    if not args.check:
        fd, tmp = tempfile.mkstemp(prefix=".mermaid-width-data.", dir=OUT.parent)
        try:
            with open(fd, "w", encoding="utf-8") as fh:
                fh.write(out)
            Path(tmp).replace(OUT)
        finally:
            if Path(tmp).exists():
                Path(tmp).unlink()
        print(f"width-data.lisp: {len(rows)} runs -> {OUT}")
        return 0

    current = OUT.read_text(encoding="utf-8")
    if current == out:
        print(
            f"mermaid width-data consistency: {OUT} matches "
            "grok-mermaid-0.2.2 dist/width-data.js"
        )
        return 0
    print(
        f"mermaid width-data consistency: {OUT} differs from the "
        "checked-in fixture; rerun scripts/gen-mermaid-width-data.py",
        file=sys.stderr,
    )
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
